enum class B1FontDescriptorPlan : std::uint8_t {
    not_applicable,
    reject,
    set_replacement,
    keep_replacement,
};

constexpr bool is_b1_main_font(std::string_view segment, std::string_view key) noexcept {
    return segment == "B1" && key == b1_main_font_key;
}

constexpr B1FontDescriptorPlan b1_font_descriptor_plan(std::string_view segment, std::string_view key,
                                                        std::uint16_t width, std::uint16_t height,
                                                        std::uint16_t glyph_count) noexcept {
    if (!is_b1_main_font(segment, key)) {
        return B1FontDescriptorPlan::not_applicable;
    }
    if (width != b1_font_descriptor_width || glyph_count != b1_font_descriptor_glyph_count) {
        return B1FontDescriptorPlan::reject;
    }
    if (height == b1_font_descriptor_original_height) {
        return B1FontDescriptorPlan::set_replacement;
    }
    return height == b1_font_descriptor_replacement_height ? B1FontDescriptorPlan::keep_replacement
                                                            : B1FontDescriptorPlan::reject;
}

